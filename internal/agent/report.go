package agent

import (
	"fmt"
	"strings"
	"time"

	"github.com/khangphantz/aatmt/internal/store"
)

// Report renders a self-contained Markdown report of a task: request, brief,
// plan with outcomes, code changes (diffs), timeline and token usage.
func (e *Engine) Report(t *store.Task) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", t.Title)
	fmt.Fprintf(&b, "| | |\n|---|---|\n| ID | `%s` |\n| Stage | %s |\n| Priority | %s |\n| Created | %s |\n",
		t.ID, t.Stage, t.Priority, t.CreatedAt.Format(time.RFC822))
	if t.DoneAt != nil {
		fmt.Fprintf(&b, "| Done | %s |\n", t.DoneAt.Format(time.RFC822))
	}
	if t.ProjectID != "" {
		if p, err := e.Store.Project(t.ProjectID); err == nil {
			fmt.Fprintf(&b, "| Project | %s |\n", p.Name)
		}
	}
	u := t.Usage
	fmt.Fprintf(&b, "| Tokens | in %d · out %d · cache read %d · cache write %d · %d calls |\n", u.Input, u.Output, u.CacheRead, u.CacheWrite, u.Calls)
	if u.Cost > 0 {
		fmt.Fprintf(&b, "| Cost | $%.4f |\n", u.Cost)
	}
	if len(t.Tags) > 0 {
		fmt.Fprintf(&b, "| Tags | %s |\n", strings.Join(t.Tags, ", "))
	}

	b.WriteString("\n## Request\n\n")
	for _, m := range t.Messages {
		fmt.Fprintf(&b, "> **%s** (%s)\n>\n", orDash(m.From), m.At.Format("2006-01-02 15:04"))
		for _, ln := range strings.Split(strings.TrimSpace(m.Text), "\n") {
			b.WriteString("> " + ln + "\n")
		}
		b.WriteString("\n")
	}
	for i, im := range t.Images {
		fmt.Fprintf(&b, "**Screenshot %d — %s**\n\n```\n%s\n```\n\n", i+1, im.Name, strings.TrimSpace(im.Transcript))
	}

	if br := t.Brief; br != nil {
		b.WriteString("## Brief\n\n" + br.Summary + "\n\n")
		mdList(&b, "Requirements", br.Requirements)
		mdList(&b, "Acceptance criteria", br.Acceptance)
		mdList(&b, "Open questions / assumptions", br.Questions)
		mdList(&b, "Risks", br.Risks)
		mdList(&b, "Relevant files", br.RelevantFiles)
		mdList(&b, "Agent memory", br.Memory)
		if br.Estimate != "" {
			fmt.Fprintf(&b, "**Estimate:** %s\n\n", br.Estimate)
		}
	}

	if len(t.Steps) > 0 {
		b.WriteString("## Plan & outcome\n\n")
		for i, s := range t.Steps {
			box := " "
			if s.Status == store.StepDone {
				box = "x"
			}
			fmt.Fprintf(&b, "- [%s] **%d. %s** _(%s", box, i+1, s.Title, s.Status)
			if s.Turns > 0 {
				fmt.Fprintf(&b, ", %d turns, %d tokens, %s", s.Turns, s.Tokens, s.Profile)
			}
			b.WriteString(")_\n")
			if s.Summary != "" {
				for _, ln := range strings.Split(strings.TrimSpace(s.Summary), "\n") {
					b.WriteString("  " + ln + "\n")
				}
			}
		}
		b.WriteString("\n")
	}

	var live []store.Change
	for _, c := range t.Changes {
		if !c.Reverted {
			live = append(live, c)
		}
	}
	if len(live) > 0 {
		b.WriteString("## Code changes\n\n")
		for _, c := range live {
			fmt.Fprintf(&b, "### `%s` (%s)\n\n", c.Path, c.Op)
			if d, err := e.FileDiff(t, c.Path); err == nil && d != "" {
				b.WriteString("```diff\n" + clip(d, e.lim().DiffMaxChars) + "\n```\n\n")
			}
		}
	}

	if evs, err := e.Store.Events(t.ID, 0, 0); err == nil {
		b.WriteString("## Timeline\n\n")
		for _, ev := range evs {
			if ev.Type == "stage" || ev.Type == "step" || ev.Type == "approval" || ev.Type == "question" || ev.Type == "note" || ev.Type == "error" {
				fmt.Fprintf(&b, "- `%s` **%s** %s %s\n", ev.At.Format("01-02 15:04"), ev.Type, ev.Title, excerpt(strings.ReplaceAll(ev.Detail, "\n", " "), e.lim().SummaryChars))
			}
		}
	}
	fmt.Fprintf(&b, "\n---\n_Generated by AATMT on %s_\n", time.Now().Format(time.RFC822))
	return b.String()
}

func orDash(s string) string {
	if s == "" {
		return "—"
	}
	return s
}

func mdList(b *strings.Builder, title string, items []string) {
	if len(items) == 0 {
		return
	}
	fmt.Fprintf(b, "**%s**\n\n", title)
	for _, it := range items {
		fmt.Fprintf(b, "- %s\n", it)
	}
	b.WriteString("\n")
}
